def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--self-check", action="store_true", help="run the scripted CPU fixture and exit")
    ap.add_argument("--live", action="store_true", help="collect against a served actor (needs GPU + corpus)")
    ap.add_argument("--questions", help="JSONL/CSV of questions for --live (uid, question[, question_requirements])")
    ap.add_argument("--out", help="immutable output directory for --live")
    ap.add_argument("--actor-base-url", default=None, help="OpenAI-compatible /v1 base URL of the served actor")
    ap.add_argument("--served-model", default="eval", help="served actor model name")
    ap.add_argument("--max-turns", type=int, default=DEFAULT_MAX_TURNS)
    ap.add_argument("--limit", type=int, default=0, help="cap number of episodes (0 = all)")
    ap.add_argument("--difficulty", default="", help="filter questions by difficulty column (e.g. easy)")
    ap.add_argument("--no-require-submit", dest="require_submit", action="store_false",
                    help="use the legacy no-tool-call terminal instead of the submit_report tool")
    ap.add_argument("--nudge-window", type=int, default=DEFAULT_NUDGE_WINDOW,
                    help="turns before the cap to start nudging + lock ALL retrieval (0 = off)")
    ap.add_argument("--submit-only-window", type=int, default=DEFAULT_SUBMIT_ONLY_WINDOW,
                    help="last N turns where submit_report is the ONLY tool (0 = off; <= nudge-window)")
    ap.set_defaults(require_submit=True)
    args = ap.parse_args(argv)

    if args.self_check:
        return _self_check()

    # Env-driven live mode for the serve harness (air/84): serve_and_eval.sh exports
    # EVAL_BASE_URL/EVAL_MODEL after /health, then runs this script with NO CLI args.
    if os.environ.get("OQ_COLLECT_LIVE") == "1":
        return _live_from_env()

    if args.live:
        if not args.actor_base_url or not args.questions or not args.out:
            ap.error("--live requires --actor-base-url, --questions and --out")
        print("WARNING: --live reuses eval_officeqa_agentic primitives; the wiring is inspection-\n"
              "verified but the SERVED MODEL's runtime behaviour is not -- run a 1-2 episode GPU smoke\n"
              "(air/84) and inspect the capture record before trusting a full collection. Needs a\n"
              "staged corpus + separate GPU/budget authorization (see handoff Section 6).",
              file=sys.stderr)
        questions = _select_questions(_load_questions(args.questions),
                                      difficulty=args.difficulty, limit=args.limit)
        if not questions:
            ap.error(f"no questions selected (difficulty={args.difficulty!r} limit={args.limit})")
        collect_live(questions, out_dir=args.out, base_url=args.actor_base_url,
                     served_model=args.served_model, max_turns=args.max_turns,
                     require_submit=args.require_submit, nudge_window=args.nudge_window,
                     submit_only_window=args.submit_only_window)
        return 0

    ap.error("provide --self-check, or --live with its required flags")
    return 2


def _load_questions(path: str) -> list[dict]:
    if path.endswith(".jsonl"):
        with open(path, encoding="utf-8") as f:
            return [json.loads(line) for line in f if line.strip()]
    import csv
    with open(path, newline="", encoding="utf-8") as f:
        return [dict(r) for r in csv.DictReader(f)]


def _select_questions(questions: list[dict], *, difficulty: str = "", limit: int = 0) -> list[dict]:
    """Filter by the ``difficulty`` column (case-insensitive) and cap to the first ``limit``.
    Shared by ``--live`` (flags) and the ``OQ_COLLECT_LIVE`` env path so a smoke can take
    1-2 easy questions from the full eval CSV without a bespoke fixture file."""
    out = questions
    if difficulty:
        d = difficulty.strip().lower()
        out = [q for q in out if str(q.get("difficulty", "")).strip().lower() == d]
    if limit and limit > 0:
        out = out[:limit]
    return out


def _live_from_env() -> int:
    """Live collection driven entirely by env vars -- the entry serve_and_eval.sh uses
    (it exports EVAL_BASE_URL/EVAL_MODEL after /health, then runs this script with no CLI
    args when EVAL_SCRIPT=officeqa/path_report_collect.py and OQ_COLLECT_LIVE=1). See air/84."""
    base_url = os.environ.get("EVAL_BASE_URL")
    out_dir = os.environ.get("OQ_COLLECT_OUT")
    q_path = os.environ.get("OQ_COLLECT_QUESTIONS") or os.environ.get("OFFICEQA_EVAL_CSV")
    if not (base_url and out_dir and q_path):
        print("OQ_COLLECT_LIVE=1 requires EVAL_BASE_URL, OQ_COLLECT_OUT and "
              "OQ_COLLECT_QUESTIONS (or OFFICEQA_EVAL_CSV).", file=sys.stderr)
        return 2
    served = os.environ.get("EVAL_MODEL", "eval")
    max_turns = int(os.environ.get("EVAL_MAX_TURNS", str(DEFAULT_MAX_TURNS)))
    difficulty = os.environ.get("OQ_COLLECT_DIFFICULTY", "")
    limit = int(os.environ.get("OQ_COLLECT_LIMIT", "0") or "0")
    require_submit = _env_bool("OQ_REQUIRE_SUBMIT", True)          # submit contract is the active default
    nudge_window = int(os.environ.get("OQ_NUDGE_WINDOW", str(DEFAULT_NUDGE_WINDOW)) or "0")
    submit_only_window = int(os.environ.get("OQ_SUBMIT_ONLY_WINDOW", str(DEFAULT_SUBMIT_ONLY_WINDOW)) or "0")
    concurrency = int(os.environ.get("OQ_COLLECT_CONCURRENCY", "1") or "1")
    questions = _select_questions(_load_questions(q_path), difficulty=difficulty, limit=limit)
    if not questions:
        print(f"no questions selected from {q_path} "
              f"(difficulty={difficulty!r} limit={limit})", file=sys.stderr)
        return 2
    print(f"[collect] env-driven live: {len(questions)} question(s) from {q_path} "
          f"(difficulty={difficulty or 'any'} limit={limit or 'all'}) actor={base_url} "
          f"model={served} turns={max_turns} submit={require_submit} window={nudge_window} "
          f"submit_only={submit_only_window} conc={concurrency} -> {out_dir}",
          flush=True)
    collect_live(questions, out_dir=out_dir, base_url=base_url,
                 served_model=served, max_turns=max_turns,
                 require_submit=require_submit, nudge_window=nudge_window,
                 submit_only_window=submit_only_window, concurrency=concurrency)
    return 0


def _env_bool(name: str, default: bool) -> bool:
    v = os.environ.get(name)
    if v is None:
        return default
    return v.strip().lower() in ("1", "true", "yes", "on")


if __name__ == "__main__":
    sys.exit(main())
