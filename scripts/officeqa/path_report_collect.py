@dataclass
class EpisodeCapture:
    episode_id: str
    obs_prefix: str = "obs_"
    _n: int = 0
    _obs: dict = field(default_factory=dict)          # oid -> mutable observation dict
    _pending: dict = field(default_factory=dict)      # oid -> target request index (delivery)
    _raw_exec: list = field(default_factory=list)     # full outputs incl. undelivered (audit)

    def new_observation(self, *, tool: str, args: dict, outcome: str, delivered_text: str,
                        generated_by_request: int) -> str:
        self._n += 1
        oid = f"{self.obs_prefix}{self._n}"
        self._obs[oid] = {
            "observation_id": oid, "order": self._n, "tool": tool,
            "args": dict(args or {}), "outcome": outcome,
            "delivered_text": delivered_text,               # nulled at finalize if undelivered
            "generated_by_request": generated_by_request,
            "delivered_to_request": None,
        }
        self._raw_exec.append({"observation_id": oid, "order": self._n, "tool": tool,
                               "args": dict(args or {}), "outcome": outcome,
                               "full_output": delivered_text})
        return oid

    def pend(self, oid: str, *, target: int) -> None:
        self._pending[oid] = target

    def deliver(self, request_index: int) -> None:
        """Mark every observation whose delivery target == request_index as delivered.
        Call this ONLY after the consuming actor request has successfully generated, so a
        failed actor turn leaves its inputs undelivered."""
        for oid, tgt in list(self._pending.items()):
            if tgt == request_index:
                self._obs[oid]["delivered_to_request"] = request_index
                del self._pending[oid]

    def finalize(self, *, question: str, question_requirements: str, terminal_text: str,
                 termination: str, raw_turns: list, max_turns: int) -> dict:
        n_delivered = 0
        for o in self._obs.values():
            if o["delivered_to_request"] is None:
                o["delivered_text"] = None                  # executed but never delivered != evidence
            else:
                n_delivered += 1
        observations = [self._obs[k] for k in sorted(self._obs, key=lambda k: self._obs[k]["order"])]
        return {
            "episode_id": self.episode_id,
            "question": question,
            "question_requirements": question_requirements,
            "terminal_text": terminal_text,
            "termination": termination,
            "answer_correct": None,                          # a reviewer labels this separately
            "observations": observations,
            "raw_executions": self._raw_exec,
            "raw_turns": raw_turns,
            "n_observations": len(observations),
            "n_delivered": n_delivered,
            "max_turns": max_turns,
            "collector_version": COLLECTOR_VERSION,
        }


def _default_render_calls(calls: list, turn: int) -> list:
    return [{"id": f"c{turn}_{i}", "type": "function", "function": {"name": n, "arguments": a}}
            for i, (n, a) in enumerate(calls)]


def _submit_args(calls: list, submit_tool: str):
    """Return the arguments of the first submit_report call in this turn, or None. A submit
    call ALWAYS terminates (even in legacy mode) -- it is the explicit finish action."""
    for name, args in calls:
        if name == submit_tool:
            return args if args is not None else {}
    return None


def _report_text_from_submit(sa) -> str:
    """Turn submit_report arguments into the terminal report JSON text.

    Tool-calling models/parsers frequently serialize a NESTED argument (here ``path``, a list
    of objects) as a JSON *string* rather than a native array -- and sometimes stringify the
    whole arguments object. Decode those so the stored terminal text is the structured report
    ``{answer, path:[...]}`` the model intended. This is lossless (the string is exactly the
    model's JSON); anything that is not valid JSON is handed through unchanged so parse_report
    still judges it (never fabricated into a list)."""
    obj = sa
    if isinstance(obj, str):
        try:
            obj = json.loads(obj)
        except Exception:  # noqa: BLE001 - not JSON: let parse_report flag it
            return obj
    if isinstance(obj, dict):
        obj = dict(obj)
        p = obj.get("path")
        if isinstance(p, str):
            try:
                obj["path"] = json.loads(p)
            except Exception:  # noqa: BLE001 - leave a non-JSON path as-is -> parse_report flags it
                pass
    return json.dumps(obj, ensure_ascii=False)


def run_episode(actor_fn: Callable[[list, int], ActorTurn], tool_fn: Callable[[str, dict], str],
                question: str, *, question_requirements: str = "", episode_id: str = "ep",
                system_prompt: str = PATH_REPORT_SYSTEM_PROMPT, final_nudge: str = PATH_REPORT_FINAL_NUDGE,
                max_turns: int = DEFAULT_MAX_TURNS, reasoning_of: Callable[[str], str] = lambda t: t,
                obs_prefix: str = "obs_",
                require_submit: bool = False, nudge_window: int = 0,
                submit_only_window: int = 0,
                locked_tools: tuple = LOCKED_TOOLS_DEFAULT, submit_tool: str = SUBMIT_TOOL,
                endgame_nudge: str = ENDGAME_NUDGE, submit_required_nudge: str = SUBMIT_REQUIRED_NUDGE,
                retrieval_locked_msg: str = RETRIEVAL_LOCKED_MSG,
                submit_only_nudge: str = SUBMIT_ONLY_NUDGE,
                submit_only_locked_msg: str = SUBMIT_ONLY_LOCKED_MSG) -> dict:
    """Drive one episode and return its capture record. ``actor_fn(messages, request_index)``
    returns ``{"text", "tool_calls":[(name,args)...], "error"}``; ``tool_fn(name, args)``
    returns the tool's delivered text. Both are injected so this is fully unit-testable with
    a scripted actor and stub tools (no model, no network).

    Terminal mechanism:
      * A ``submit_report`` tool call ALWAYS ends the episode; its arguments ARE the report.
      * ``require_submit=False`` (legacy, default): a turn with no tool calls is also terminal
        (the old {answer,path} printed as text). Preserves air/83/84/86 behaviour exactly.
      * ``require_submit=True`` (Replace contract): submit is the ONLY finish -- a no-tool-call
        turn is NOT terminal; it is nudged to submit and the episode continues.
    Two-tier endgame:
      * outer (``nudge_window > 0``): in the last ``nudge_window`` turns a nudge is injected and
        ``locked_tools`` are refused (redirect, outcome 'locked'); compute + submit stay available.
      * inner (``submit_only_window > 0``, meant to be <= nudge_window): in the last
        ``submit_only_window`` turns EVERY tool except ``submit_tool`` is refused -- the actor may
        only submit. A turn cap NEVER synthesizes a report."""
    cap = EpisodeCapture(episode_id, obs_prefix)
    messages = [{"role": "system", "content": system_prompt},
                {"role": "user", "content": question}]
    raw_turns: list = []
    terminal_text = ""
    termination = "incomplete"

    for turn in range(max_turns):
        is_last = (turn == max_turns - 1)
        remaining = max_turns - turn
        in_submit_only = (submit_only_window > 0 and remaining <= submit_only_window)   # inner
        in_window = (nudge_window > 0 and remaining <= nudge_window)                     # outer retrieval-lock
        if is_last:
            messages.append({"role": "user", "content": final_nudge})
        elif in_submit_only:
            messages.append({"role": "user", "content": submit_only_nudge.format(n=remaining)})
        elif in_window:
            messages.append({"role": "user", "content": endgame_nudge.format(n=remaining)})
        try:
            out = actor_fn(messages, turn)
        except Exception as e:  # noqa: BLE001 - an actor fault ends the episode; nothing is delivered
            raw_turns.append({"request_index": turn, "error": f"{type(e).__name__}: {e}"})
            termination = "actor_error"
            break
        if out.get("error"):
            raw_turns.append({"request_index": turn, "text": out.get("text", ""), "error": out["error"]})
            termination = "actor_error"
            break

        # The actor request at `turn` generated successfully -> results targeted at it were
        # actually consumed and are now delivered.
        cap.deliver(turn)

        text = out.get("text", "") or ""
        calls = list(out.get("tool_calls") or [])
        raw_turns.append({"request_index": turn, "text": text,
                          "tool_calls": [{"name": n, "args": a} for n, a in calls]})

        # explicit finish: a submit_report call terminates and carries the report as its args
        # (decoding a path/args the model serialized as a JSON string -- a common tool-call quirk).
        sa = _submit_args(calls, submit_tool)
        if sa is not None:
            terminal_text = _report_text_from_submit(sa)
            termination = "terminal_report"
            break

        if not calls:
            if require_submit:
                # Replace contract: a no-tool-call turn does NOT finish. Nudge to submit, continue.
                if is_last:
                    terminal_text = text
                    termination = "no_submit_at_cap"
                    break
                messages.append({"role": "assistant", "content": reasoning_of(text)})
                messages.append({"role": "user", "content": submit_required_nudge})
                continue
            terminal_text = text
            termination = "terminal_report" if text.strip() else "empty_terminal"
            break
        if is_last:
            # The nudge forbade tools; the model called a non-submit tool anyway. Do NOT
            # dispatch or synthesize.
            terminal_text = text
            termination = "turn_cap_tool_call"
            break

        messages.append({"role": "assistant", "content": reasoning_of(text),
                         "tool_calls": _default_render_calls(calls, turn)})
        for i, (name, args) in enumerate(calls):
            if in_submit_only and name != submit_tool:
                # innermost endgame: only submit_report may run; compute + all retrieval get a
                # redirect tagged 'locked' -- never a real observation of the corpus.
                output, outcome = submit_only_locked_msg, "locked"
            elif in_window and name in locked_tools:
                # retrieval locked in the outer window: respond (template needs one per call) but
                # deliver a redirect, tagged 'locked' -- never a real observation of the corpus.
                output, outcome = retrieval_locked_msg, "locked"
            else:
                try:
                    output = tool_fn(name, args)
                    outcome = classify_outcome(output)
                except Exception as e:  # noqa: BLE001 - a tool fault is a delivered error, not a crash
                    output = f"Error: tool {name} failed: {type(e).__name__}: {e}"
                    outcome = "error"
            oid = cap.new_observation(tool=name, args=args if isinstance(args, dict) else {},
                                      outcome=outcome, delivered_text=output, generated_by_request=turn)
            messages.append({"role": "tool", "name": name, "tool_call_id": f"c{turn}_{i}",
                             "content": OBS_MARKER.format(oid=oid) + "\n" + output})
            cap.pend(oid, target=turn + 1)

    return cap.finalize(question=question, question_requirements=question_requirements,
                        terminal_text=terminal_text, termination=termination,
                        raw_turns=raw_turns, max_turns=max_turns)


def _part_name(eid: str) -> str:
    """Stable, filesystem-safe part filename for an episode id (uid-based -> resume-stable)."""
    return (re.sub(r"[^A-Za-z0-9._-]", "_", str(eid)) or "ep") + ".json"


def _resume_pending(questions: list[dict], parts_dir: str) -> tuple[list[dict], int]:
    """Split questions into (still-to-run, n_already_done) by checking parts_dir for each
    question's durable per-episode file. A question with a uid/episode_id whose part exists is
    skipped (already captured); one without a stable id is always run (its part name would be
    index-derived and non-resumable). Pure + CPU-testable."""
    todo, n_done = [], 0
    existing = set(os.listdir(parts_dir)) if os.path.isdir(parts_dir) else set()
    for q in questions:
        eid = str(q.get("uid") or q.get("episode_id") or "")
        if eid and _part_name(eid) in existing:
            n_done += 1
        else:
            todo.append(q)
    return todo, n_done


def _collect_records(questions: list[dict], episode_runner: Callable[[int, dict], dict],
                     *, concurrency: int = 1,
                     on_result: "Callable[[int, dict], None] | None" = None) -> list[dict]:
    """Run ``episode_runner(index, question) -> record`` for every question and return the
    records in INPUT ORDER. ``concurrency <= 1`` runs them one at a time (the proven
    sequential path). ``concurrency > 1`` runs up to that many episodes at once on a thread
    pool -- each episode is an independent, self-contained ``run_episode`` (its own capture,
    event loop and session) and the work is I/O-bound on the actor endpoint, so threads give
    real overlap. Input order is preserved either way. CPU-testable with a stub runner.

    ``on_result(index, record)`` (optional) is invoked on the calling thread as each episode
    COMPLETES -- used to persist captures incrementally so a kill/timeout keeps finished work."""
    if concurrency <= 1:
        results = []
        for i, q in enumerate(questions):
            rec = episode_runner(i, q)
            if on_result is not None:
                on_result(i, rec)
            results.append(rec)
        return results
    from concurrent.futures import ThreadPoolExecutor, as_completed
    results: list = [None] * len(questions)
    with ThreadPoolExecutor(max_workers=concurrency) as pool:
        futs = {pool.submit(episode_runner, i, q): i for i, q in enumerate(questions)}
        for fut in as_completed(futs):
            idx = futs[fut]
            rec = fut.result()   # episode_runner is exception-safe -> always a record
            results[idx] = rec
            if on_result is not None:
                on_result(idx, rec)
    return results


