def classify_outcome(text: str) -> str:
    """Coarse outcome tag for a delivered tool result. Call completion is NOT semantic
    support (pilot Section 3.3); this only records error/empty/ok, never acceptance."""
    if not text or not text.strip():
        return "empty"
    s = text.lstrip()
    if s.startswith("Error:"):
        return "error"
    head = s[:80]
    if s.startswith("No ") and re.search(r"found|match|document", head):
        return "empty"
    return "ok"


