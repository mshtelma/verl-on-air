def _scripted_actor(script: list) -> Callable[[list, int], ActorTurn]:
    """Return an actor_fn that replays a fixed list of ActorTurns by request index."""
    def actor_fn(_messages, req):
        return script[req] if req < len(script) else {"text": '{"answer":"DATA NOT AVAILABLE","path":[]}',
                                                       "tool_calls": [], "error": None}
    return actor_fn


def _stub_tools(mapping: dict) -> Callable[[str, dict], str]:
    def tool_fn(name, args):
        key = (name, json.dumps(args, sort_keys=True))
        return mapping.get(key, mapping.get(name, f"No results for {name}."))
    return tool_fn


def _self_check() -> int:
    # A clean 3-turn episode: two reads (turn 0), a compute depending on them (turn 1),
    # then the terminal report (turn 2). This exercises IDs, delivery and chronology.
    script = [
        {"text": "search then read both years",
         "tool_calls": [("read_document", {"file_name": "b1941.txt"}),
                        ("read_document", {"file_name": "b1942.txt"})], "error": None},
        {"text": "now subtract",
         "tool_calls": [("compute", {"code": "print(1.47-1.30)"})], "error": None},
        {"text": ('{"answer":"0.17 trillion dollars","path":['
                  '{"id":"a","observation":"obs_1","claim":"1941 total 1.47 trillion"},'
                  '{"id":"b","observation":"obs_2","claim":"1942 total 1.30 trillion"},'
                  '{"id":"c","observation":"obs_3","depends_on":["a","b"],'
                  '"claim":"compute 1.47-1.30 = 0.17"}]}'),
         "tool_calls": [], "error": None},
    ]
    tools = _stub_tools({
        ("read_document", json.dumps({"file_name": "b1941.txt"}, sort_keys=True)): "1941 grand total: 1.47 trillion",
        ("read_document", json.dumps({"file_name": "b1942.txt"}, sort_keys=True)): "1942 grand total: 1.30 trillion",
        ("compute", json.dumps({"code": "print(1.47-1.30)"}, sort_keys=True)): "0.17",
    })
    rec = run_episode(_scripted_actor(script), tools, "How much did the total decrease?",
                      episode_id="selfcheck", max_turns=8)

    # 1) capture shape
    obs = {o["observation_id"]: o for o in rec["observations"]}
    ok = True
    checks = [
        ("3 observations issued in order", [o["observation_id"] for o in rec["observations"]] == ["obs_1", "obs_2", "obs_3"]),
        ("reads generated at turn 0", obs["obs_1"]["generated_by_request"] == 0 and obs["obs_2"]["generated_by_request"] == 0),
        ("reads delivered at turn 1", obs["obs_1"]["delivered_to_request"] == 1 and obs["obs_2"]["delivered_to_request"] == 1),
        ("compute generated at turn 1, delivered at turn 2", obs["obs_3"]["generated_by_request"] == 1 and obs["obs_3"]["delivered_to_request"] == 2),
        ("delivered_text is exact tool output", obs["obs_1"]["delivered_text"] == "1941 grand total: 1.47 trillion"),
        ("terminal captured, no FINAL_ANSWER forcing", rec["termination"] == "terminal_report" and "<FINAL_ANSWER>" not in rec["terminal_text"]),
    ]
    # 2) the record must feed the offline scorer and score SCORED under a stub judge
    ledger = pr.EpisodeLedger.from_record(rec)
    report = pr.parse_report(rec["terminal_text"])
    ref = pr.check_references(report, ledger)
    verdict = pr.parse_support_verdict('{"path_status":"supported","path_score":0.9,"issues":[]}')
    prev = pr.candidate_preview(report=report, ref=ref, verdict=verdict, answer_correct=True)
    checks.append(("valid report parses", report.ok))
    checks.append(("references resolve (good chronology)", ref.valid))
    checks.append(("scores SCORED end-to-end", prev.status == pr.SCORED))

    print("self-check:")
    for name, passed in checks:
        ok = ok and passed
        print(f"  [{'OK ' if passed else 'BAD'}] {name}")
    print(f"\ncapture: termination={rec['termination']} obs={rec['n_observations']} delivered={rec['n_delivered']}")
    if not ok:
        print("\nSELF-CHECK FAILED")
        return 1
    print("\nSELF-CHECK PASSED (CPU-only; no network/model/GPU used)")
    return 0


