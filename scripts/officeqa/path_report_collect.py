#!/usr/bin/env python3
"""Isolated collector for the OfficeQA path-report pilot (handoff Section 3, pilot Section 7 step 2).

This produces the RUNTIME-OWNED capture records that ``path_report_pilot.py`` scores.
Its subtle, safety-critical logic -- issuing episode-scoped **observation IDs**, tracking
which results were actually **delivered** to the actor, and taking the **terminal event**
without letting the legacy ``<FINAL_ANSWER>`` forcing manufacture a second commitment -- is
a PURE, CPU-testable state machine (``EpisodeCapture`` + ``run_episode``). The live actor/
tool I/O is a thin wrapper around the proven primitives in ``scripts/eval_officeqa_agentic.py``.

Capture-record schema emitted (consumed by path_report / path_report_pilot):

    {episode_id, question, question_requirements, terminal_text, termination,
     answer_correct (null until a reviewer labels it),
     observations: [{observation_id, order, tool, args, outcome,
                     delivered_text|null, generated_by_request, delivered_to_request|null}],
     raw_executions: [...full outputs incl. undelivered, for audit...],
     raw_turns: [...every assistant text + calls, so failed exploration is retained...]}

Guarantees enforced here (pilot Sections 2-3):
  * observation IDs are RUNTIME-ISSUED and delivered to the actor as ``[observation obs_N]``;
    the actor can only *reference* them, never mint them;
  * a result executed but never delivered (e.g. the consuming actor request errored) has its
    ``delivered_text`` nulled and ``delivered_to_request`` = null -- it is not evidence;
  * multiple calls in ONE turn are all generated by that request and delivered together at the
    NEXT request, so a compute call cannot "see" a read issued in the same parallel batch
    (this is what makes path_report's impossible-chronology check fire);
  * the terminal report is the LAST assistant event only; tool outputs are never scanned for it;
  * no answer is ever synthesized or repaired at the turn cap.

Modes: ``--self-check`` (scripted actor + stub tools; CPU only) and a GATED ``--live`` that
needs an actor endpoint + staged corpus (separate GPU/budget authorization).
"""

