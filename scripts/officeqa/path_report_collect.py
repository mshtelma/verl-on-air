def collect_live(questions: list[dict], *, out_dir: str, base_url: str, served_model: str,
                 max_turns: int = DEFAULT_MAX_TURNS,
                 require_submit: bool = True, nudge_window: int = DEFAULT_NUDGE_WINDOW,
                 submit_only_window: int = DEFAULT_SUBMIT_ONLY_WINDOW,
                 concurrency: int = 1) -> str:
    """Collect fresh actor-authored path reports against a served actor model.

    Reuses eval's tokenizer/chat-template rendering and qwen3_coder tool-call parsing, and
    eval's five tool impls, so it inherits the proven format handling; only the capture
    bookkeeping and the terminal-JSON contract are new (and are the CPU-tested core above).
    Sequential per episode (pilot Section 7: rollout may be sequential). Requires a running
    actor endpoint AND a staged corpus -- neither is set up by this script.

    Defaults to the SUBMIT contract (``require_submit=True``): the actor is advertised a
    ``submit_report`` tool and finishes by calling it, and search/grep are locked in the last
    ``nudge_window`` turns (the report-yield fix). Pass ``require_submit=False`` to reproduce
    the legacy no-tool-call terminal used by the first collection (air/85)."""
    import asyncio
    # eval reads its config from env at import time; set what the CLI provided first.
    os.environ.setdefault("EVAL_BASE_URL", base_url)
    os.environ.setdefault("EVAL_MODEL", served_model)
    os.environ.setdefault("EVAL_MAX_TURNS", str(max_turns))
    sys.path.insert(0, os.path.dirname(_HERE))                     # scripts/
    import eval_officeqa_agentic as ev                              # noqa: E402  (lazy; needs aiohttp+transformers)

    if ev.aiohttp is None:
        raise SystemExit("aiohttp unavailable: the live actor path needs the serving image.")

    tok = ev._load_tokenizer()
    parse = ev._load_parser(tok)
    ev._oqt._load_chunks()                                          # pre-warm (freezes loop if lazy)
    ev._oqt._get_bm25()

    # submit mode advertises submit_report alongside eval's 5 tools + uses the submit prompts.
    tools = list(ev.TOOLS) + ([SUBMIT_TOOL_SCHEMA] if require_submit else [])
    sys_prompt = PATH_REPORT_SYSTEM_PROMPT_SUBMIT if require_submit else PATH_REPORT_SYSTEM_PROMPT
    fin_nudge = PATH_REPORT_FINAL_NUDGE_SUBMIT if require_submit else PATH_REPORT_FINAL_NUDGE
    # Make the episode structure PROMINENT + accurate: fill the system prompt with the real budget
    # and window sizes so the actor PLANS for them. A model whose tools vanish unannounced drifts
    # out-of-distribution; one told the rules up front stays in its normal agentic regime.
    if require_submit:
        sys_prompt = (sys_prompt.replace("[[MAX_TURNS]]", str(max_turns))
                                .replace("[[RETRIEVAL_LOCK]]", str(nudge_window))
                                .replace("[[SUBMIT_ONLY]]", str(submit_only_window)))
    # outer endgame window forbids ALL retrieval (search/grep/read/list); compute + submit stay.
    lock_tools = RETRIEVAL_TOOLS

    timeout = ev.aiohttp.ClientTimeout(total=ev.REQ_TIMEOUT)

    def episode_runner(idx: int, q: dict) -> dict:
        # Each episode is fully self-contained: its OWN event loop + aiohttp session (a
        # session binds to its creating loop, so concurrent episodes cannot share one).
        # The render (tokenize=False Jinja), qwen3_coder parse and read-only tool impls
        # are safe under concurrent reads, so threads give real actor-endpoint overlap.
        eid = str(q.get("uid") or q.get("episode_id") or f"ep{idx}")
        loop = asyncio.new_event_loop()
        asyncio.set_event_loop(loop)
        try:
            session = loop.run_until_complete(_open_session(ev, timeout))
            try:
                def actor_fn(messages, _req, _sess=session, _loop=loop):
                    text, _c, _tr = _loop.run_until_complete(
                        ev._assistant_turn(_sess, ev._render(tok, messages, tools=tools)))
                    return {"text": text, "tool_calls": parse(text), "error": None}

                def tool_fn(name, args):
                    impl = ev.TOOL_IMPLS.get(name)
                    if impl is None:
                        return f"Error: unknown tool {name!r}."
                    return impl(args if isinstance(args, dict) else {})

                rec = run_episode(actor_fn, tool_fn, q["question"],
                                  question_requirements=q.get("question_requirements", ""),
                                  episode_id=eid,
                                  max_turns=max_turns, reasoning_of=ev._split_reasoning,
                                  system_prompt=sys_prompt, final_nudge=fin_nudge,
                                  require_submit=require_submit, nudge_window=nudge_window,
                                  locked_tools=lock_tools, submit_only_window=submit_only_window)
            finally:
                loop.run_until_complete(session.close())
        except Exception as e:  # noqa: BLE001 - one episode's fault must never kill the batch
            print(f"[collect] {eid}: collector_error {type(e).__name__}: {e}", flush=True)
            rec = EpisodeCapture(eid).finalize(
                question=q["question"], question_requirements=q.get("question_requirements", ""),
                terminal_text=f"[collector_error {type(e).__name__}: {e}]",
                termination="collector_error", raw_turns=[], max_turns=max_turns)
        finally:
            loop.close()
        print(f"[collect] {rec['episode_id']}: {rec['termination']} "
              f"obs={rec['n_observations']} delivered={rec['n_delivered']}", flush=True)
        return rec

    # "Write results as they come" DURABLY + RESUMABLY. An 80-turn deep batch can outrun the job
    # wall-clock, and losing every finished episode to a kill (as the air/113 smoke did -- 170 min
    # -> 0 output) is far worse than a slow run. out_dir is an object-storage-backed Volume (FUSE):
    # a single long-open captures.jsonl is only uploaded on close(), so a kill would lose it even
    # after flush(). Instead, each episode is written to its OWN small file under parts/ and CLOSED
    # immediately -- FUSE uploads a file on close, so every finished capture is durable the instant
    # its episode ends. On (re-)start we SKIP any question already in parts/, so a retry / top-up
    # run RESUMES instead of redoing work or dying on an overwrite guard (the air/114 retry hit
    # exactly that guard). captures.jsonl is then consolidated from ALL parts (resumed + new).
    parts_dir = os.path.join(out_dir, "parts")
    os.makedirs(parts_dir, exist_ok=True)

    def _persist(idx: int, rec: dict) -> None:
        fn = _part_name(rec.get("episode_id") or f"ep{idx}")
        with open(os.path.join(parts_dir, fn), "w", encoding="utf-8") as pf:
            pf.write(json.dumps(rec, ensure_ascii=False))   # one object, closed now -> durable on FUSE

    # RESUME: drop questions whose part file already exists (stable uid-based name).
    if _env_bool("OQ_COLLECT_RESUME", True):
        questions, n_done = _resume_pending(questions, parts_dir)
        if n_done:
            print(f"[collect] resume: {n_done} already in parts/, {len(questions)} still to run",
                  flush=True)

    records = _collect_records(questions, episode_runner, concurrency=concurrency,
                               on_result=_persist)

    # Consolidate ALL parts (this run + any resumed) into captures.jsonl.
    import glob as _glob
    all_recs = []
    for fp in sorted(_glob.glob(os.path.join(parts_dir, "*.json"))):
        try:
            all_recs.append(json.load(open(fp, encoding="utf-8")))
        except Exception as e:  # noqa: BLE001 - a corrupt part must not lose the rest
            print(f"[collect] skipping unreadable part {os.path.basename(fp)}: {e}", flush=True)
    path = os.path.join(out_dir, "captures.jsonl")
    with open(path, "w", encoding="utf-8") as f:
        for r in all_recs:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    manifest = {"created_utc": _dt.datetime.now(_dt.timezone.utc).isoformat(),
                "n_episodes": len(all_recs), "n_this_run": len(records),
                "actor": f"{base_url} model={served_model}",
                "max_turns": max_turns, "require_submit": require_submit, "nudge_window": nudge_window,
                "submit_only_window": submit_only_window,
                "retrieval_lock_tools": list(RETRIEVAL_TOOLS) if require_submit else [],
                "concurrency": concurrency,
                "contract": "submit_report" if require_submit else "no_tool_call_terminal",
                "collector_version": COLLECTOR_VERSION,
                "note": "fresh actor-authored reports; scores are produced offline by path_report_pilot.py"}
    with open(os.path.join(out_dir, "manifest.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False)
    from collections import Counter
    term_hist = dict(Counter(r["termination"] for r in all_recs))
    print(f"[collect] wrote {len(all_recs)} captures ({len(records)} this run) -> {path}", flush=True)
    print(f"[collect] terminations: {term_hist}", flush=True)
    return path


async def _open_session(ev, timeout):
    return ev.aiohttp.ClientSession(timeout=timeout)


